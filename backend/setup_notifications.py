def main():
    """Main setup function"""
    
    print("🚀 Welcome to SEP Monitoring Dashboard Notification Setup!")
    print()
    
    # Show instructions first
    show_setup_instructions()
    
    # Ask if user wants to proceed
    response = input("Do you have your credentials ready? (Y/n): ").lower()
    if response == 'n':
        print("Please get your credentials and run this script again.")
        return
    
    # Create .env file
    if create_env_file():
        print()
        print("🎉 Setup complete! Your notification system is ready to use.")
    else:
        print()
        print("❌ Setup failed. Please check the error messages above.")

if __name__ == "__main__":
    main()


